// Backwards-compatibility export for nodes expecting PROMPT_TRACKER_THEME
export const PROMPT_TRACKER_THEME = THEMES.tracker.palette;

export function getThemePalette(themeKey) {
    const theme = THEMES[themeKey] || THEMES.tracker;
    return theme.palette;
}

export function styleButton(btn, isDanger = false, palette = THEMES.tracker.palette) {
    btn.style.background = isDanger ? "transparent" : palette.bgDark;
    btn.style.color = isDanger ? "#f87171" : palette.textPrimary;
    btn.style.border = `1px solid ${isDanger ? "#7f1d1d" : palette.border}`;
    btn.style.borderRadius = "4px";
    btn.style.padding = "3px 6px";
    btn.style.cursor = "pointer";
    btn.style.fontSize = "11px";

    btn.onmouseenter = () => {
        btn.style.backgroundColor = isDanger ? "#7f1d1d" : palette.borderFocus;
        if (isDanger) btn.style.color = "#ffffff";
    };
    btn.onmouseleave = () => {
        btn.style.background = isDanger ? "transparent" : palette.bgDark;
        btn.style.color = isDanger ? "#f87171" : palette.textPrimary;
    };
}

export function styleInput(inputEl, palette = THEMES.tracker.palette) {
    inputEl.style.backgroundColor = palette.bgDark;
    inputEl.style.color = palette.textPrimary;
    inputEl.style.border = `1px solid ${palette.border}`;
    inputEl.style.borderRadius = "4px";
    inputEl.style.padding = "3px 6px";
    inputEl.style.outline = "none";

    inputEl.onfocus = () => inputEl.style.borderColor = palette.borderFocus;
    inputEl.onblur = () => inputEl.style.borderColor = palette.border;
}

export function createStatusBar(palette) {
    const statusBar = document.createElement("div");
    statusBar.innerText = "Ready";
    statusBar.style.fontSize = "10px";
    statusBar.style.padding = "2px 4px";
    statusBar.style.backgroundColor = palette.bgCard;
    statusBar.style.border = `1px solid ${palette.border}`;
    statusBar.style.borderRadius = "4px";
    statusBar.style.color = palette.textSecondary;

    const setStatus = (msg, isError = false) => {
        statusBar.innerText = msg;
        statusBar.style.color = isError ? "#f87171" : palette.textSecondary;
    };

    return { statusBar, setStatus };
}

export function createThemeDropdown(node, currentPalette, onThemeChange) {
    const select = document.createElement("select");
    styleInput(select, currentPalette);
    select.style.fontSize = "10px";

    Object.keys(THEMES).forEach(key => {
        const opt = document.createElement("option");
        opt.value = key;
        opt.innerText = THEMES[key].name;
        if (node.properties?.activeTheme === key) opt.selected = true;
        select.appendChild(opt);
    });

    select.onchange = (e) => {
        e.stopPropagation();
        const newKey = select.value;
        if (!node.properties) node.properties = {};
        node.properties.activeTheme = newKey;

        const selectedTheme = THEMES[newKey];
        node.color = selectedTheme.color;
        node.bgcolor = selectedTheme.bgcolor;
        node.setDirtyCanvas(true, true);

        if (onThemeChange) {
            onThemeChange(selectedTheme.palette, newKey);
        }
    };

    return select;
}